# [미션 1] 파일 쓰기 ('w' 모드 활용)
# 질문 1. with 구문을 사용해서 "test.txt" 파일을 'w' 모드로 열고, 
# "오늘부터 파이썬 파일 입출력을 배운다!" 라는 문장을 적어보삼 (encoding="utf-8" 필수!)
# (힌트: f.write("내용") 사용)

# ----------------------------------------------------------------
with open("test.txt", "w", encoding="utf-8") as f:
	f.write("오늘부터 파이썬 파일 입출력을 배운다!")


# ----------------------------------------------------------------


# [미션 2] 파일 내용 추가하기 ('a' 모드 활용)
# 질문 2. 기존 일기에 내용을 덧붙이기 위해 "test.txt" 파일을 'a' 모드로 열고,
# 다음 줄에 "\n우비야 산책 가자!" 라는 문장을 추가해보삼
# (힌트: \n은 줄바꿈 문자임!)

# ----------------------------------------------------------------
with open("test.txt", "a", encoding="utf-8") as f:
	f.write("\n우비야 산책 가자!")


# ----------------------------------------------------------------


# [미션 3] 파일 읽어와서 출력하기 ('r' 모드 활용)
# 질문 3. "test.txt" 파일을 'r' 모드로 열고, 그 안의 내용을 통째로 읽어서 출력해보삼
# (힌트: text = f.read() 로 읽어온 뒤 print(text) 하삼)

# ----------------------------------------------------------------
with open("test.txt", "r", encoding="utf-8") as f:
	text = f.read()

print(text)


