# [8일차 미션: 1주차 종합 복습 계산기 만들기]
# 목표: 함수, 조건문, input()을 활용하여 사칙연산 계산기를 완성하시오.

# 1. 사칙연산 함수 정의하기
def add(a, b):
	return a + b

# 질문 1. 빼기(-) 기능을 하는 sub(a, b) 함수를 만들어 값을 리턴하삼
# (힌트: def sub(a, b): 라고 쓰고 return ... 하삼)
def sub(a, b):
	return a - b


# 질문 2. 곱하기(*) 기능을 하는 mul(a, b) 함수를 만들어 값을 리턴하삼
def mul(a, b):
	return a * b


# ----------------------------------------------------------------
# 2. 사용자 입력 받기 (여기는 바로 실행할 수 있게 짜두었음!)
# ----------------------------------------------------------------
print("=== 파이썬 계산기 ===")
num1 = int(input("첫 번째 정수를 입력하삼: "))
op = input("연산자를 입력하삼 (+, -, *): ")
num2 = int(input("두 번째 정수를 입력하삼: "))


# ----------------------------------------------------------------
# 3. 조건문(if-elif-else)을 활용한 연산자 판별 및 출력
# ----------------------------------------------------------------

# + 처리 부분!
if op == "+":
	print(f"결과: {add(num1, num2)}")

# 질문 3. 그게 아니고 op가 "-" 이면 sub 함수를 호출해 결과를 출력하삼
# (힌트: elif op == "-": 입력 후 다음 줄 들여쓰기해서 print! 연산자 - 입력하면 여기서 걸림!)
elif op == "-":
	print(f"결과: {sub(num1, num2)}")

# 질문 4. 그게 아니고 op가 "*" 이면 mul 함수를 호출해 결과를 출력하삼
elif op == "*":
	print(f"결과: {mul(num1, num2)}")


# 질문 5. 그 외에 다른 연산자가 들어오면 "지원하지 않는 연산자임"을 출력하삼
# (힌트: else: 활용!)
else:
	print("지원하지 않는 연산자임.")