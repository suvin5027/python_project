# ----------------------------------------------------------------
# 💡 1. split() - 문자열 쪼개기 (자바의 String.split())
# ----------------------------------------------------------------
# - 기능: 기준 글자를 가지고 문자열을 잘라서 '리스트(배열)'로 반환함
# - 특징: 괄호 안에 아무것도 안 넣으면 기본값인 '공백(띄어쓰기)' 기준임
# - 예시:
#   text = "사과,바나나,체리"
#   result = text.split(",") -> ['사과', '바나나', '체리']

# ----------------------------------------------------------------
# 💡 2. join() - 리스트를 문자열로 합치기 (자바의 String.join())
# ----------------------------------------------------------------
# - 기능: 쪼개져 있는 리스트(배열) 알맹이들을 하나의 긴 문자열로 묶어줌
# - 특징: 구조가 독특함! -> "연결할글자".join(리스트명)
# - 예시:
#   fruits = ['사과', '바나나', '체리']
#   result = " & ".join(fruits) -> "사과 & 바나나 & 체리"

# ----------------------------------------------------------------
# 💡 3. replace() - 글자 바꾸기 (자바의 String.replace())
# ----------------------------------------------------------------
# - 기능: 문자열에서 특정 글자를 찾아서 새 글자로 싹 교체해 버림
# - 구조: 문자열.replace("옛날글자", "새글자")
# - [주의] 파이썬 문자열은 불변(Immutable) 객체임!
#   원본 변수가 직접 바뀌지 않으므로 반드시 새 변수에 대입해서 써야 함
# - 예시:
#   text = "Hello World"
#   result = text.replace("World", "Python") -> "Hello Python"

# ----------------------------------------------------------------
# 💡 이건 내 꿀팁인데~ (연쇄 호출: Chaining)
# ----------------------------------------------------------------
# - 자바 스트림이나 리액트처럼 파이썬도 함수를 기차처럼 이어서 쓸 수 있음
# - 예: "사과,바나나".replace("바나나", "망고").split(",")
#   -> '바나나'를 '망고'로 먼저 바꾼 뒤 콤마로 쪼개서 ['사과', '망고']가 됨
# ----------------------------------------------------------------