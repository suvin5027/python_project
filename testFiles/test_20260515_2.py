# 질문 1. 두 수를 더해서 결과를 리턴하는 'add' 함수를 만드삼
# (힌트: def add(a, b): 라고 쓰고 return a + b 하삼)
def add(a, b):
	return a + b


# 질문 2. 위에서 만든 add 함수를 호출해서 10과 20을 더한 값을 출력해보삼
message = add(10, 20)
print(message)


# 질문 3. 이름을 매개변수로 받아서 "OOO님, 환영합니다!"를 출력하는
# 'welcome' 함수를 만드삼 (리턴값 없이 내부에서 바로 print 하삼)
def welcome(name):
	print(f"{name}님, 환영합니다!")


# 질문 4. welcome 함수에 "수빈"을 넣어서 호출해보삼
welcome("수빈")


