# ================================================================
# [9일차 예습] split()을 활용한 한 줄 계산기 (구조 분해 할당)
# 핵심 개념: split()은 기본적으로 '공백(스페이스바)'을 기준으로 글자를 쪼갬!
# ================================================================

def add(a, b):
	return a + b

def sub(a, b):
	return a - b

def mul(a, b):
	return a * b

print("=== 한 줄 계산기 ===")

# ----------------------------------------------------------------
# 🚨 [필독] split() 사용 시 띄어쓰기 규칙과 에러 원리
# ----------------------------------------------------------------
# 정답 예시: 10 + 20 (스페이스바로 정확히 칸을 띄워야 함!)
# -> 파이썬이 공백을 기준으로 3덩어리(['10', '+', '20'])로 예쁘게 잘라서
#	num1, op, num2에 차례대로 쏙쏙 넣어줌 (구조 분해 할당)
#
# 에러 예시: 10+20 (띄어쓰기를 안 하고 붙여 쓴 경우)
# -> 파이썬은 공백이 없으면 전체를 그냥 '큰 덩어리 1개'(['10+20'])로 인식함
#	"난 덩어리 1개밖에 없는데 왜 변수 3개에 나눠 담으라고 해?!" 하면서
#	ValueError (not enough values to unpack) 에러를 뿜으며 뻗어버림!
# ----------------------------------------------------------------

num1, op, num2 = input("계산할 식을 입력하삼 (주의: 꼭 10 + 20 처럼 띄어쓰기 하기!): ").split()


# split()으로 쪼개서 들어온 데이터는 아직 '문자열("10", "20")' 상태임!
# 산술 연산을 위해 명시적으로 int()를 씌워 숫자로 형변환(Casting) 해줌
num1 = int(num1)
num2 = int(num2)


# 사용자가 입력한 op(연산자)에 따라 분기 처리
if op == "+":
	print(f"결과: {add(num1, num2)}")
elif op == "-":
	print(f"결과: {sub(num1, num2)}")
elif op == "*":
	print(f"결과: {mul(num1, num2)}")
else:
	print("지원하지 않는 연산자임.")