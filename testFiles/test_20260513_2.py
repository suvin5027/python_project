# [미션: 장바구니 리스트 관리하기]
# 목표: 리스트의 생성, 추가, 슬라이싱을 익히시오.

# 1. 'shopping_list'라는 이름의 리스트를 만들고 "우유", "계란", "빵"을 담으삼
# ----------------------------------------------------------------
shopping_list = ["우유", "계란", "빵"]

# 2. .append()를 사용해서 "초콜릿"을 리스트 맨 뒤에 추가해보삼
# ----------------------------------------------------------------
shopping_list.append("초콜릿")

# 3. 인덱싱을 사용해서 "계란"만 출력해보삼
# ----------------------------------------------------------------
print(shopping_list[1])

# 4. 슬라이싱을 사용해서 "우유"부터 "계란"까지만 잘라서 출력해보삼
# (힌트: [0:2] 처럼 끝 번호를 주의하삼!)
# [4번 피드백: 슬라이싱 번호]
# [시작:끝]에서 '끝'은 포함되지 않음
# 인덱스 0(우유), 1(계란)을 가져오려면 2까지 지정해야 함 [0:2]
# ----------------------------------------------------------------
print(shopping_list[0:2])

# 5. (심화) for문을 사용해서 리스트에 담긴 항목을 하나씩 출력해보삼
# (예: "장바구니 품목: 우유")
# [5번 피드백: for문과 리스트]
# range(4)를 써서 인덱스 i로 접근한 방식도 아주 훌륭한 논리임!
# 하지만 파이썬에서는 더 간결한 '파이썬다운(Pythonic)' 방식이 있음
# ----------------------------------------------------------------
#for i in range(4):
#	print(f"장바구니 품목 : {shopping_list[i]}")
for i in shopping_list:
	print(f"장바구니 품목 : {i}")
# 이렇게 쓰면 range()를 쓰지 않아도 리스트 안의 알맹이를 하나씩 꺼내줌
# 리액트에서 배열.map(item => ...) 쓰는 거랑 거의 똑같은 느낌임!