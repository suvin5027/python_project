# [미션: 수빈이의 학점 계산기 만들기]
# 목표: 점수에 따라 다른 메시지를 출력하는 조건문을 완성하시오.

# 1. 점수 변수 설정 (원하는 숫자로 바꿔가며 테스트해보기)
score = 10

# ----------------------------------------------------------------
# 여기서부터 코드를 작성해보삼! (음슴체 가이드)
# ----------------------------------------------------------------

# 질문 1. 만약(if) score가 90점 이상이면 "A학점임"을 출력하게 짜보삼
# (힌트: 조건식 끝에 : 붙이고 다음 줄 들여쓰기 필수)
# if score >= 90: 처럼 변수를 앞에 두는 걸 더 많이 쓰긴 함
if 90 <= score:
	print("A학점임")


# 질문 2. 그게 아니고(elif) score가 80점 이상 90점 미만이면 "B학점임" 출력
# (힌트: 파이썬 특유의 80 <= score < 90 문법을 써보삼)
elif 80 <= score < 90:
	print("B학점임")


# 질문 3. 위의 조건에 모두 해당하지 않으면(else) "재시험 대상임" 출력
else:
	print("재시험 대상임")

# ----------------------------------------------------------------