# ----------------------------------------------------------------
# 1. 연산 기능 함수로 만들기 (자바의 메서드 역할)
# ----------------------------------------------------------------
# - def 키워드를 사용해 함수를 정의하고, return으로 계산 결과를 던져줌
# - 자바와 달리 리턴 타입(int 등)을 미리 적지 않아도 돼서 유연함

def add(a, b):
	return a + b

def sub(a, b):
	return a - b

def mul(a, b):
	return a * b


# ----------------------------------------------------------------
# 2. 사용자 입력받기 (자바의 Scanner 역할)
# ----------------------------------------------------------------
print("=== 파이썬 계산기 ===")

# [주의] input()으로 들어오는 모든 데이터는 기본적으로 '문자열(String)'임!
# 산술 연산을 해야 하므로 명시적으로 int()를 감싸서 정수형으로 형변환(Casting) 필수
num1 = int(input("첫 번째 숫자 입력: ")) 
op = input("연산자 입력 (+, -, *): ")
num2 = int(input("두 번째 숫자 입력: "))


# ----------------------------------------------------------------
# 3. 조건문으로 계산 및 출력하기 (if-elif-else 분기)
# ----------------------------------------------------------------
# - 사용자가 입력한 op 변수의 값에 따라 위에서부터 순서대로 조건을 검사함
# - 자바의 if-else if-else 구조와 완벽히 매칭됨

if op == "+":
	# 연산자가 + 이면 위에서 정의한 add 함수를 호출함
	print(f"결과: {add(num1, num2)}")

elif op == "-":
	# + 가 아니고 - 이면 sub 함수를 호출함 (물어봤던 해결책!)
	print(f"결과: {sub(num1, num2)}")

elif op == "*":
	# * 이면 mul 함수를 호출함
	print(f"결과: {mul(num1, num2)}")

else:
	# 위 조건(+, -, *)에 모두 해당하지 않는 엉뚱한 연산자가 들어왔을 때 실행되는 안전장치
	print("지원하지 않는 연산자임.")

