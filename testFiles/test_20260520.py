# ----------------------------------------------------------------
# 💡 1. 파일 열기: open() 함수와 모드(Mode)
# ----------------------------------------------------------------
# - 파이썬에서 파일을 다룰 때는 open() 함수를 사용함
# - 파일을 어떤 용도로 열지 '모드'를 정해줘야 함
#   * 'w' (Write) : 쓰기 모드 (파일이 없으면 만들고, 있으면 기존 내용 싹 지우고 새로 씀)
#   * 'a' (Append) : 추가 모드 (기존 내용 뒤에 이어서 씀)
#   * 'r' (Read) : 읽기 모드 (파일 내용을 읽어옴)

# ----------------------------------------------------------------
# 💡 2. 옛날 방식 vs 요즘 방식 (with문)
# ----------------------------------------------------------------
# - 옛날 방식: 파일을 open() 하면 자바처럼 마지막에 반드시 close()를 해줘야 함
#   f = open("test.txt", "w")
#   f.write("Hello")
#   f.close()  # <- 이거 까먹으면 파일이 잠기거나 리소스 낭비됨!
#
# - 요즘 방식 (with 구문) ★실무 국룰★
#   * with 블록이 끝나는 순간 파이썬이 알아서 자동으로 close()를 해줌!
#   with open("test.txt", "w", encoding="utf-8") as f:
#       f.write("Hello")

# ----------------------------------------------------------------
# 💡 3. 한글 깨짐 방지: encoding="utf-8"
# ----------------------------------------------------------------
# - 윈도우 환경에서 파이썬으로 메모장을 만들 때 한글을 넣으면 깨지는 경우가 많음
# - open() 함수 안에 encoding="utf-8"을 명시해 주는 것이 실무 매너이자 필수 팁!
