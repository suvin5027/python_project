# 5. 변수 (Variable)
# =============================================================================

# 변수는 값을 저장하는 메모리 공간입니다.
# 할당문: 변수이름 = 값

spam = 40           # spam에 40을 저장합니다.
eggs = 2
print(spam + eggs)  # → 42

spam = spam + 2     # 새 값으로 덮어씁니다. (이전 값 40은 사라집니다.)
print(spam)         # → 42

# 변수 이름 규칙:
# ✅ 문자, 숫자, 밑줄(_)만 사용 가능합니다.
# ✅ 대소문자를 구분합니다. (spam ≠ SPAM ≠ Spam)
# ❌ 숫자로 시작할 수 없습니다. (4account → 에러)
# ❌ 공백을 사용할 수 없습니다. (current balance → 에러)
# ❌ 파이썬 키워드는 사용할 수 없습니다. (if, for, return 등)

# 좋은 변수 이름 예시입니다.
