# 1. 표현식 (Expression)
# =============================================================================

# 표현식 = 값(value) + 연산자(operator) → 항상 하나의 값으로 평가됩니다.
# 파이썬에서 가장 기본적인 프로그래밍 명령어입니다.

2 + 2       # → 4
10 - 3      # → 7
'hello'     # → 'hello'  (값 하나만 있어도 표현식입니다.)


# =============================================================================
# 2. 수학 연산자
# =============================================================================

# 연산자    의미              예시         결과
# **       지수 (거듭제곱)    2 ** 3    →  8
# %        나머지            22 % 8    →  6
# //       정수 나눗셈        22 // 8   →  2   (소수점 버림)
# /        나눗셈             22 / 8    →  2.75
# *        곱셈              3 * 5     →  15
# -        뺄셈              5 - 2     →  3
# +        덧셈              2 + 2     →  4

# 연산 우선순위: ** → *, /, //, % → +, - (왼쪽→오른쪽)
# 괄호를 사용하면 우선순위를 직접 조절할 수 있습니다.

print(2 + 3 * 6)        # → 20  (곱셈 먼저)
print((2 + 3) * 6)      # → 30  (괄호 먼저)
print(2 ** 8)           # → 256
print(23 / 7)           # → 3.285...
print(23 // 7)          # → 3   (소수점 버림)
print(23 % 7)           # → 2   (나머지)


# =============================================================================
# 3. 데이터 타입 (Data Type)
# =============================================================================

# 파이썬의 대표적인 3가지 데이터 타입입니다.
#
# int   (정수)       : -2, -1, 0, 1, 2, 3 ...
# float (부동소수점)  : -1.25, 0.5, 3.14 ...
