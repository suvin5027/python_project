# 8. 컴퓨터가 이진수로 데이터를 저장하는 방법
# =============================================================================

# 컴퓨터는 모든 데이터를 0과 1(이진수, binary)로 저장합니다.
# 이진수는 2진법 숫자 체계로, 10진수와 같은 수를 표현할 수 있습니다.
# 이진수 한 자리를 비트(bit), 8비트를 바이트(byte)라고 합니다.

# 파일 용량 단위 (2의 거듭제곱 기준):
# 1 킬로바이트 (KB) = 2^10 = 1,024 바이트
# 1 메가바이트 (MB) = 2^20 = 1,048,576 바이트
# 1 기가바이트 (GB) = 2^30 = 1,073,741,824 바이트
# 1 테라바이트 (TB) = 2^40 = 1,099,511,627,776 바이트

# 하드 드라이브 제조사는 1TB를 1,099,511,627,776 바이트가 아닌
# 1,000,000,000,000 바이트로 계산하여 광고합니다.
# 이로 인해 실제 사용 가능 용량이 광고보다 적게 표시됩니다.
# (이 개념은 2장 예제 프로그램 dishonestcapacity.py에서 활용합니다.)


