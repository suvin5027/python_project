# =============================================================================
# 6. 내장 함수들
# =============================================================================

# print() - 화면에 값을 출력합니다.
print('Hello, world!')
print()             # 빈 줄을 출력합니다.

# input() - 사용자 입력을 받습니다. (항상 str을 반환합니다.)
# my_name = input('이름을 입력하세요: ')

# len() - 문자열의 길이(글자 수)를 반환합니다.
print(len('hello'))         # → 5
print(len('안녕하세요'))     # → 5
print(len(''))              # → 0

# str() - 값을 문자열로 변환합니다.
print(str(42))              # → '42'
print(str(3.14))            # → '3.14'

# int() - 값을 정수로 변환합니다. (소수점이 있으면 버림합니다.)
print(int('42'))            # → 42
print(int('-99'))           # → -99
print(int(7.9))             # → 7   (버림, 내림이 아닙니다.)
print(int(1.25))            # → 1

# 주의: 정수로 평가할 수 없는 값을 전달하면 ValueError가 발생합니다.
# int('99.99')   # → ValueError: invalid literal for int() with base 10: '99.99'
# int('twelve')  # → ValueError: invalid literal for int() with base 10: 'twelve'

# float() - 값을 부동소수점으로 변환합니다.
print(float('3.14'))        # → 3.14
print(float(10))            # → 10.0

# type() - 값의 데이터 타입을 확인합니다.
print(type(42))             # → <class 'int'>
print(type(3.14))           # → <class 'float'>
print(type('hello'))        # → <class 'str'>

# round() - 반올림합니다.
print(round(3.14))          # → 3
print(round(7.7))           # → 8
print(round(3.14, 1))       # → 3.1  (소수 1자리까지)
# 주의: .5인 경우 가장 가까운 짝수로 반올림합니다. (은행 반올림)
print(round(3.5))           # → 4
print(round(2.5))           # → 2   (올림이 아닌 짝수 쪽으로 반올림됩니다.)

# abs() - 절댓값을 반환합니다. (음수 → 양수)
print(abs(-25))             # → 25
print(abs(3.14))            # → 3.14
print(abs(-3.14))           # → 3.14


