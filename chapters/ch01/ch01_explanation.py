print(3 + 4)        # → 7   (int)
print(3 + 4.0)      # → 7.0 (float)
print(16 / 4)       # → 4.0 (나눗셈은 항상 float을 반환합니다.)

# 문자열은 항상 따옴표로 감싸야 합니다.
