# =============================================================================
# 연습 1. 수학 연산자
# =============================================================================

# (1) ** 연산자로 2의 10제곱을 구합니다.
print(2 ** 10)

# (2) % 연산자로 100을 7로 나눈 나머지를 구합니다.
print(100 % 7)

# (3) // 연산자로 100을 7로 나눈 정수 몫을 구합니다. (소수점 버림)
print(100 // 7)

# (4) 괄호로 우선순위를 지정하여 계산합니다.
print((3 + 5) * (10 - 4))


# =============================================================================
# 연습 2. 변수에 값 저장하기
# =============================================================================

# 이름을 문자열로 저장합니다.
my_name = "박수빈"

# 나이를 정수로 저장합니다.
my_age = 32

# str()로 정수를 문자열로 변환한 후 + 로 연결하여 출력합니다.
print("내 이름은 " + my_name + "이고 나이는 " + str(my_age) + "살 입니다.")


# =============================================================================
# 연습 3. 데이터 타입 확인
# =============================================================================

# type() 함수로 각 값의 데이터 타입을 확인합니다.
print(type(42))         # → <class 'int'>
print(type(3.14))       # → <class 'float'>
print(type("hello"))    # → <class 'str'>
print(type(True))       # → <class 'bool'>


# =============================================================================
# 연습 4. 문자열 연결과 복제
# =============================================================================

# * 연산자로 문자열을 3번 반복합니다.
word = "Python"
print(word * 3)

# + 연산자로 문자열 세 개를 이어붙입니다.
print("나는 " + "파이썬을 " + "배우고 있습니다.")


# =============================================================================
# 연습 5. 타입 변환 (str, int, float)
# =============================================================================

# int()로 문자열을 정수로 변환한 후 덧셈을 수행합니다.
str1 = "99"
str2 = int(str1)
print(str2 + 1)

# str()로 정수를 문자열로 변환한 후 연결하여 출력합니다.
int1 = 2025
int2 = str(int1)
print("올해는 " + int2 + "년 입니다.")

# float()로 문자열을 부동소수점으로 변환한 후 곱셈을 수행합니다.
str3 = "3.14"
flt1 = float(str3)
print(flt1 * 2)


# =============================================================================
# 연습 6. len(), round(), abs()
# =============================================================================

# len()으로 문자열의 글자 수를 구합니다.
print(len("Automate the Boring Stuff"))

# round()의 두 번째 인자로 반올림할 소수 자릿수를 지정합니다.
print(round(3.567, 2))

# abs()로 음수의 절댓값을 구합니다.
print(abs(-42))


# =============================================================================
# 연습 7. 종합 미니 프로그램
# =============================================================================

# 이름과 나이를 변수에 저장합니다.
name = "박수빈"
age = 32

# str()로 정수를 변환하고, len()으로 이름의 글자 수를 구하여 출력합니다.
print("안녕하세요! 저는 [" + name + "]이고, 내년이면 [" + str(age + 1) + "]살이 됩니다.")
print("이름의 글자 수는 [" + str(len(name)) + "]글자 입니다.")
