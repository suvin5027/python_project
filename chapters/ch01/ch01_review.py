# 1. 표현식 (Expression)
#    → 값(value) + 연산자(operator)의 조합입니다.
#    → 항상 하나의 값으로 평가(축소)됩니다.
#    → 예) 2 + 3 → 5,  'Hello' + '!' → 'Hello!'

# 2. 수학 연산자 우선순위 (높은 순)
#    → **  (지수)
#    → *, /, //, %  (곱셈 / 나눗셈 계열, 왼쪽→오른쪽)
#    → +, -  (덧셈 / 뺄셈, 왼쪽→오른쪽)
#    → 괄호()로 우선순위를 직접 조절할 수 있습니다.

# 3. 데이터 타입 3가지
#    → int   : 정수      예) 0, 42, -7
#    → float : 부동소수점 예) 3.14, -1.0
#    → str   : 문자열    예) 'hello', '42'
#    → 주의: 42(int) / 42.0(float) / '42'(str) 는 모두 다른 타입입니다.
#    → int와 float을 함께 연산하면 결과는 항상 float입니다.
#    → 나눗셈(/)은 두 정수를 나눠도 항상 float을 반환합니다.

# 4. 문자열 연산
#    → +  : 두 문자열을 이어붙입니다. (연결)
#    → *  : 문자열을 정수만큼 반복합니다. (복제)
#    → 문자열과 정수를 + 로 연결하면 TypeError가 발생합니다.
#       → str()로 변환 후 연결해야 합니다.

# 5. 변수 (Variable)
#    → 할당문(=)으로 값을 저장합니다.
#    → 새 값을 할당하면 이전 값은 사라집니다. (덮어쓰기)
#    → 변수 이름: 문자·숫자·밑줄 사용, 숫자로 시작 불가, 공백 불가

# 6. 주요 내장 함수
#    → print()  : 화면에 출력합니다.
#    → input()  : 사용자 입력을 받습니다. (항상 str 반환)
#    → len()    : 문자열의 글자 수를 반환합니다.
#    → str()    : 값을 문자열로 변환합니다.
#    → int()    : 값을 정수로 변환합니다. (소수점은 버림)
#    → float()  : 값을 부동소수점으로 변환합니다.
#    → type()   : 값의 데이터 타입을 반환합니다.
#    → round()  : 반올림합니다. 두 번째 인자로 자릿수 지정 가능합니다.
#    → abs()    : 절댓값을 반환합니다.


