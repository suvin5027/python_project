# 제9장 - 정규 표현식 복습 및 실수 정리

import re

# ============================================================
# 핵심 개념 총정리
# ============================================================

# ✅ 정규 표현식 사용 4단계
# 1단계: import re
# 2단계: re.compile(패턴) → Pattern 객체 생성
# 3단계: pattern.search(문자열) → Match 객체 반환 (없으면 None)
# 4단계: match.group() → 매칭된 문자열 반환

# ✅ 주요 특수 문자 / 단축 클래스
# \d   → 숫자 [0-9]
# \D   → 숫자가 아닌 것
# \w   → 단어 문자 [a-zA-Z0-9_]
# \s   → 공백/탭/줄바꿈
# .    → 줄바꿈 제외 모든 문자 1개
# ^    → 문자열 시작 ([ ] 밖에서)
# $    → 문자열 끝

# ✅ 수량자
# ?    → 0번 또는 1번 (선택적)
# *    → 0번 이상
# +    → 1번 이상
# {n}  → 정확히 n번
# {n,m}→ n번 이상 m번 이하
# 수량자 뒤에 ? 붙이면 비탐욕적(Lazy) 매칭

# ============================================================
# 실수 정리
# ============================================================

# ─────────────────────────────────────────────
# ❌ 실수 1: search() 결과가 None인데 group() 호출
# ─────────────────────────────────────────────

pattern = re.compile(r'\d+')

# ❌ 잘못된 코드 — search() 결과가 None이면 AttributeError 발생합니다.
# result = pattern.search('abc').group()  # AttributeError!

# ✅ 올바른 코드 — 반드시 None 체크 후 group()을 호출합니다.
match = pattern.search('abc')
if match:
	print(match.group())
else:
	print('매칭 없음')


# ─────────────────────────────────────────────
# ❌ 실수 2: findall()에 그룹이 있을 때 반환값 혼동
# ─────────────────────────────────────────────

text = 'Cell: 415-555-9999 Work: 212-555-0000'

# ❌ 잘못된 이해 — 그룹이 있으면 문자열 리스트가 아니라 튜플 리스트를 반환합니다.
# ['415-555-9999', '212-555-0000'] 이라고 예상하면 틀립니다.
with_group = re.compile(r'(\d{3})-(\d{3}-\d{4})')
print(with_group.findall(text))
# 실제 출력: [('415', '555-9999'), ('212', '555-0000')]  ← 튜플 리스트!

# ✅ 올바른 이해 — 그룹이 없어야 문자열 리스트를 반환합니다.
no_group = re.compile(r'\d{3}-\d{3}-\d{4}')
print(no_group.findall(text))
# 출력: ['415-555-9999', '212-555-0000']  ← 문자열 리스트


# ─────────────────────────────────────────────
# ❌ 실수 3: ^ 기호의 두 가지 의미 혼동
# ─────────────────────────────────────────────

# ❌ 잘못된 이해 — ^ 는 항상 부정을 의미한다고 생각합니다.

# ✅ 올바른 이해 — ^ 위치에 따라 의미가 달라집니다.
# [ ] 밖에서 ^ → 문자열의 시작(앵커)
starts_re = re.compile(r'^\d+')
print(starts_re.search('123abc') is not None)   # True  (숫자로 시작)
print(starts_re.search('abc123') is None)       # True  (숫자로 시작 안 함)

# [ ] 안에서 ^ → 부정 문자 클래스 (해당 문자가 아닌 것)
non_digit = re.compile(r'[^\d]')
print(non_digit.findall('a1b2'))  # ['a', 'b']  (숫자가 아닌 것)


# ─────────────────────────────────────────────
# ❌ 실수 4: r'' 원시 문자열 안 쓰기
# ─────────────────────────────────────────────

# ❌ 잘못된 코드 — 일반 문자열에서 \d, \n 등이 이스케이프로 처리될 수 있습니다.
# bad_pattern = re.compile('\d{3}')  # 의도치 않은 동작 가능

# ✅ 올바른 코드 — 정규 표현식은 항상 r'' 원시 문자열로 작성합니다.
good_pattern = re.compile(r'\d{3}')
print(good_pattern.findall('123-456'))  # ['123', '456']


# ─────────────────────────────────────────────
# ❌ 실수 5: 탐욕적/비탐욕적 매칭 혼동
# ─────────────────────────────────────────────

html = '<title>Hello</title>'

# ❌ 잘못된 이해 — <.*>이 <title>만 찾을 거라고 생각합니다.
greedy = re.compile(r'<.*>')
print('탐욕적:', greedy.search(html).group())
# 실제 출력: <title>Hello</title>  ← 가장 긴 매칭을 가져옵니다!

# ✅ 올바른 코드 — 가장 짧은 매칭을 원하면 ? 를 붙여 비탐욕적으로 만듭니다.
lazy = re.compile(r'<.*?>')
print('비탐욕적:', lazy.search(html).group())
# 출력: <title>  ← 가장 짧은 매칭


# ─────────────────────────────────────────────
# ❌ 실수 6: group()과 groups() 혼동
# ─────────────────────────────────────────────

phone_re = re.compile(r'(\d{3})-(\d{3}-\d{4})')
mo = phone_re.search('415-555-4242')

# ❌ 잘못된 코드 — groups()는 튜플을 반환하므로 인덱스로 접근해야 합니다.
# print(mo.groups(1))  # TypeError! groups()는 인수를 받지 않습니다.

# ✅ 올바른 코드
print(mo.group(1))    # '415'           — 첫 번째 그룹만
print(mo.group(2))    # '555-4242'      — 두 번째 그룹만
print(mo.groups())    # ('415', '555-4242') — 모든 그룹을 튜플로
area, main = mo.groups()  # 다중 할당 가능


# ============================================================
# 핵심 메서드 요약
# ============================================================

# re.compile(패턴)           → Pattern 객체 생성
# pattern.search(문자열)     → 첫 번째 매칭 위치의 Match 객체 반환 (없으면 None)
# pattern.findall(문자열)    → 모든 매칭을 리스트로 반환
# pattern.sub(교체, 문자열)  → 매칭 부분을 교체한 새 문자열 반환
# match.group()              → 전체 매칭 문자열
# match.group(n)             → n번째 그룹 문자열
# match.groups()             → 모든 그룹을 튜플로 반환

# ============================================================
# 플래그 요약
# ============================================================

