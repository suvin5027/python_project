# print(함수()) 형태로 쓸 때는 함수 안에 print 대신 return을 사용합니다.
def check_odd_even(number):
	if number % 2 == 0:
		return str(number) + "은(는) 짝수 입니다."
	else:
		return str(number) + "은(는) 홀수 입니다."

for i in range(1, 11):
	print(check_odd_even(i))
