# 틀린 코드
# def safe_divide(a, b):
#     try:
#         return a / b
#     except ZeroDivisionError:
#         return print("0으로 나눌 수 없습니다.")  ← return print(...)

# 원인
# print()는 항상 None을 반환합니다.
# return print("...") 는 사실 return None 과 완전히 동일합니다.
# 따라서 print(safe_divide(10, 0)) 을 호출하면
#   1. 함수 안 print() 가 실행되어 "0으로 나눌 수 없습니다." 출력
#   2. return None 이 실행되어 None 반환
#   3. 바깥의 print(None) 이 실행되어 None 추가 출력
# → 결과적으로 두 줄이 출력됩니다.

# ✅ 올바른 코드
def safe_divide(a, b):
	try:
		return a / b
	except ZeroDivisionError:
		return "0으로 나눌 수 없습니다."   # print 대신 문자열을 return 합니다.

print(safe_divide(10, 2))   # → 5.0
print(safe_divide(10, 0))   # → 0으로 나눌 수 없습니다.
print(safe_divide(9, 3))    # → 3.0

# 핵심 규칙
# except 블록에서도 return 으로 값을 돌려주면 호출 방식을 통일할 수 있습니다.
# return print(...) 는 절대 사용하지 않습니다.
