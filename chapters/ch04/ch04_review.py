# 1. 함수 정의 (def 문)
#    → def 함수이름(): 으로 함수를 정의합니다.
#    → 함수 본문은 def 문이 실행될 때가 아니라, 함수가 호출될 때 실행됩니다.
#    → 코드 중복을 없애고, 수정도 한 곳에서만 하면 됩니다.

# 2. 인수(argument)와 매개변수(parameter)
#    → 매개변수: 함수 정의에서 괄호 안에 오는 변수입니다.
#    → 인수: 함수 호출 시 전달하는 값입니다.
#    → 매개변수는 함수가 반환되면 사라집니다. (지역 변수)

# 3. return 문과 반환값
#    → return 으로 함수가 호출한 곳으로 값을 돌려줍니다.
#    → result = 함수() 형태로 반환값을 변수에 저장할 수 있습니다.
#    → return 이 없으면 None 이 반환됩니다.

# 4. print() vs return 핵심 차이
#    → print() : 화면에 보여주는 것입니다. (출력)
#    → return  : 함수 밖으로 값을 돌려주는 것입니다. (반환)
#    → print(함수()) 형태로 쓰려면 함수 안에 return 이 있어야 합니다.

# 5. None 값
#    → 값이 없음을 나타내는 특별한 값입니다. 타입은 NoneType 입니다.
#    → return 이 없는 함수, 또는 return 만 있는 함수는 None 을 반환합니다.
#    → print() 함수 자체도 None 을 반환합니다.

# 6. 키워드 인수 (Named Parameters)
#    → print(end='') : 줄바꿈 없이 출력합니다.
#    → print(sep=',') : 여러 값 사이의 구분자를 지정합니다.

# 7. 지역/전역 범위 (Local/Global Scope)
#    → 지역 변수: 함수 안에서만 존재하고, 함수 종료 시 사라집니다.
#    → 전역 변수: 함수 밖에서 정의되어 어디서든 접근 가능합니다.
#    → 함수 안에서 전역 변수를 수정하려면 global 문을 사용합니다.

# 8. try / except 예외 처리
#    → try 블록에서 에러 발생 시 즉시 except 블록으로 이동합니다.
#    → except 블록 실행 후 프로그램은 정상적으로 계속 진행합니다.
#    → except 블록 실행 후 try 블록으로 돌아가지 않습니다.


