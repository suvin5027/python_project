# 1. 파이썬은 인터프리터(Interpreter) 언어
#    → 코드를 위에서 아래로 한 줄씩 읽어서 바로 실행
#    → 컴파일 없이 즉시 결과 확인 가능

# 2. 대화형 셸 (Interactive Shell / REPL)
#    → 터미널에서 python 입력하면 >>> 프롬프트 등장
#    → Read(읽기) → Eval(실행) → Print(출력) → Loop(반복)
#    → 코드 한 줄씩 바로 테스트 가능
#    → 종료: exit()

# 3. 타입 (Type)
#    → 파이썬의 모든 값에는 타입이 있음
#    → str  : 문자열  예) "안녕", "27"
#    → int  : 정수    예) 27, 0
#    → 타입이 다른 값끼리는 연산 전에 타입 변환 필요

# 4. 에러가 나면?
#    → 에러 메시지 그대로 구글 검색
#    → Stack Overflow 적극 활용
#    → Traceback → 에러가 발생한 위치
#    → TypeError, SyntaxError 등 → 에러 종류


