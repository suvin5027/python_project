# 1. 딕셔너리 기본
#    - 중괄호 {} 사용, 키-값 쌍으로 구성됩니다.
#    - 키는 문자열, 정수 등 다양한 타입 가능합니다.
#    - 순서가 없습니다. (리스트와 다름)
#    - 없는 키에 접근하면 KeyError 발생합니다.

# 2. 딕셔너리 메서드
#    - keys()       : 키 목록을 반환합니다.
#    - values()     : 값 목록을 반환합니다.
#    - items()      : (키, 값) 튜플 쌍을 반환합니다.
#    - get(키, 기본값) : 키가 없어도 오류 없이 기본값을 반환합니다.
#    - setdefault(키, 기본값) : 키가 없을 때만 기본값을 추가합니다.

# 3. in / not in
#    - 딕셔너리에서 in은 기본적으로 키를 검색합니다.
#    - 값을 검색하려면 .values()를 사용합니다.

# 4. 중첩 딕셔너리
#    - dict['키1']['키2'] 형태로 접근합니다.
#    - 복잡한 데이터를 구조화할 때 유용합니다.


# ============================================================
# 실수 정리
