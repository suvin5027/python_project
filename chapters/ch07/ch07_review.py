# ----------------------------------------
# ❌ 실수 1: not in 대신 in 사용
# ----------------------------------------
person = {'name': '수빈', 'age': 25}

# ❌ 틀린 코드 — "있는지" 확인
print("email" in person)      # False (email이 있는지 확인한 것)

# ✅ 올바른 코드 — "없는지" 확인
print("email" not in person)  # True (email이 없는지 확인한 것)

# 핵심: 없는지 확인 → not in / 있는지 확인 → in
# 6장에서도 같은 실수를 했으니 특히 주의합니다!


# ----------------------------------------
# ❌ 실수 2: items() 언패킹 안 하기
# ----------------------------------------
students = {'수빈': {'math': 95}, '지훈': {'math': 72}}

# ❌ 틀린 코드 — 튜플 형태로 출력됨
for v in students.items():
	print(v)
# ('수빈', {'math': 95})
# ('지훈', {'math': 72})

# ✅ 올바른 코드 — k, v로 언패킹해서 따로 사용
for k, v in students.items():
	print(k + ":", v)
# 수빈: {'math': 95}
# 지훈: {'math': 72}

# 핵심: items()는 (키, 값) 튜플을 반환합니다.
#       k, v로 언패킹해야 따로 사용할 수 있습니다.


# ----------------------------------------
# 참고: get()과 딕셔너리 접근 비교
# ----------------------------------------
inventory = {'potion': 5}

# dict['키'] → 없으면 KeyError (오류!)
# inventory['arrow']  # → KeyError 발생

# get(키) → 없으면 None 반환 (오류 아님)
print(inventory.get('arrow'))        # None

# get(키, 기본값) → 없으면 기본값 반환
print(inventory.get('arrow', 0))     # 0
print(inventory.get('arrow', '없음')) # '없음'

# 핵심: get()은 KeyError를 방지하는 안전장치입니다.
#       두 번째 인자는 "키가 없을 때만" 사용되는 기본값(default)입니다.
#       두 번째 인자를 생략하면 None을 반환합니다. (Java의 null과 같은 개념)


# ----------------------------------------
# 참고: setdefault() vs 직접 대입
# ----------------------------------------
config = {'theme': 'dark'}

# setdefault: 키가 없을 때만 추가 (있으면 무시)
config.setdefault('theme', 'light')   # 이미 있으므로 변경 안 됨
config.setdefault('font_size', 14)    # 없으므로 추가됨
print(config)  # {'theme': 'dark', 'font_size': 14}

# 직접 대입: 항상 덮어씀
config['theme'] = 'light'   # 있어도 무조건 변경됨
print(config)  # {'theme': 'light', 'font_size': 14}

# 핵심: "없을 때만 초기값 설정" → setdefault()
#       "무조건 설정"          → 직접 대입
