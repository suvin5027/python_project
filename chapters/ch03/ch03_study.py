# 연습 1. while 루프
# =============================================================================

# count 변수를 0으로 초기화하고,
# count가 3보다 작은 동안 'Hello!'를 출력하고 count를 1씩 증가시킵니다.
count = 0
while count < 3:
	print("Hello!")
	count = count + 1


