# 연습 4. bool() 함수
# =============================================================================

# bool()로 Truthy/Falsy 여부를 확인합니다.
# ""(쌍따옴표)와 ''(따옴표)는 파이썬에서 완전히 동일합니다. 차이 없습니다.
print(bool(0))        # → False
print(bool(0.0))      # → False
print(bool(''))       # → False
print(bool(99))       # → True
print(bool('python')) # → True


# =============================================================================
# 연습 5. for 루프와 range()
# =============================================================================

# (1) range(5) : 0부터 4까지 출력합니다.
for i in range(5):
	print(i)

# (2) range(1, 6) : 1부터 5까지 출력합니다.
for i in range(1, 6):
	print(i)

# (3) range(0, 11, 2) : 0부터 10까지 2씩 증가하며 출력합니다.
#     stop(11)은 포함되지 않으므로 "0~11"이 아닌 "0~10"까지입니다.
for i in range(0, 11, 2):
	print(i)

# (4) range(5, -1, -1) : 5부터 0까지 역순으로 출력합니다.
for i in range(5, -1, -1):
	print(i)


# =============================================================================
# 연습 6. for 루프 합산
# =============================================================================

# 1부터 10까지 합산합니다.
total = 0
for i in range(1, 11):
	total = total + i
print(total)   # → 55


