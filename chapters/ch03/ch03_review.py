# 1. while 루프
#    → 조건이 True인 동안 코드 블록을 계속 반복합니다.
#    → if 문과 달리 조건이 True면 블록을 반복해서 실행합니다.
#    → 조건이 False가 되는 순간 루프를 종료합니다.

# 2. break 문
#    → 루프 전체를 즉시 탈출합니다.
#    → while True: (무한 루프)와 함께 자주 사용합니다.
#    → 무한 루프에서 break 없이 조건이 항상 True이면 프로그램이 끝나지 않습니다.
#    → 무한 루프에 빠지면 Ctrl+C로 강제 종료할 수 있습니다.

# 3. continue 문
#    → 현재 반복의 나머지 코드를 건너뛰고 루프의 처음으로 돌아갑니다.
#    → 루프를 완전히 끝내지 않고 현재 반복만 건너뜁니다.
#    → break와 헷갈리지 않도록 주의합니다.
#      - break    : 루프 전체 종료
#      - continue : 현재 반복만 건너뜀, 루프는 유지

# 4. Truthy / Falsy 값
#    → 파이썬의 모든 값은 불리언 문맥에서 True 또는 False처럼 동작합니다.
#    → Falsy 값 (거짓처럼 동작): 0, 0.0, '' (빈 문자열)
#    → 나머지 모든 값은 Truthy입니다.
#    → bool() 함수로 직접 확인할 수 있습니다.

# 5. for 루프와 range()
#    → range()가 반환하는 값을 순서대로 변수에 담으며 반복합니다.
#    → range(stop)          : 0부터 stop-1까지
#    → range(start, stop)   : start부터 stop-1까지
#    → range(start, stop, step) : start부터 stop-1까지 step 간격으로
#    → range(10), range(0, 10), range(0, 10, 1) 은 모두 동일합니다.
#    → step을 음수로 지정하면 역순으로 셀 수 있습니다. 예) range(5, -1, -1)

# 6. 모듈 임포트 (import)
#    → import 모듈이름 으로 표준 라이브러리 모듈을 불러옵니다.
#    → 함수 호출: 모듈이름.함수이름()
#    → from 모듈이름 import * 는 모듈 이름 없이 바로 호출할 수 있지만
#      어느 모듈에서 왔는지 알기 어려워 일반적으로 권장하지 않습니다.

# 7. sys.exit()
#    → 프로그램을 즉시 종료합니다.
#    → import sys 를 먼저 해야 사용할 수 있습니다.


