# ---------------------------------------------------------------
# ❌ 실수 2 : range(0, 11, 2) 를 "0~11까지"로 잘못 이해
# ---------------------------------------------------------------

# 오해: range(0, 11, 2) 는 "0부터 11까지 2씩 증가한다"
# → 0, 2, 4, 6, 8, 10, 12 가 출력될 것 같지만...

# 실제 결과
for i in range(0, 11, 2):
	print(i, end=' ')   # → 0 2 4 6 8 10
print()

# 원인
# range(start, stop, step)에서 stop은 항상 포함되지 않습니다.
# range(0, 11, 2) → 0부터 10까지 2씩 증가 (11은 포함 안 됩니다.)
# 이 규칙은 range() 의 모든 형태에 동일하게 적용됩니다.

# 확인 예시
# range(5)      → 0, 1, 2, 3, 4   (5 포함 안 됩니다.)
# range(1, 5)   → 1, 2, 3, 4      (5 포함 안 됩니다.)
# range(0, 6, 2) → 0, 2, 4        (6 포함 안 됩니다.)
