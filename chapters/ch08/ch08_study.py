# ────────────────────────────────────────────────────────────
# [1] 탈출 시퀀스 (Escape Sequences)
# ────────────────────────────────────────────────────────────

# \n으로 줄바꿈, \"로 큰따옴표, \\로 백슬래시를 표현합니다.
print("Hello!\nI\'m \"Python\".\nPath: C:\\Users\\me")


# ────────────────────────────────────────────────────────────
# [2] Raw String
# ────────────────────────────────────────────────────────────

# r'' 접두사를 사용하면 백슬래시를 그대로 출력합니다.
print(r'C:\new_folder\test.py')


# ────────────────────────────────────────────────────────────
# [3] 멀티라인 문자열
# ────────────────────────────────────────────────────────────

# 삼중 따옴표로 여러 줄 문자열을 만듭니다.
text1 = '''안녕하세요,

오늘 날씨는 맑습니다.

감사합니다.
'''
print(text1)


# ────────────────────────────────────────────────────────────
# [4] 문자열 인덱스와 슬라이스
# ────────────────────────────────────────────────────────────

word = 'Python'

# 앞에서부터: word[0], 뒤에서부터: word[-1], 범위: word[시작:끝]
print(word[0])     # P  (첫 번째 문자)
print(word[-1])    # n  (마지막 문자)
print(word[0:3])   # Pyt (처음 3글자)
print(word[-3:])   # hon (마지막 3글자, -3부터 끝까지)


# ────────────────────────────────────────────────────────────
# [5] in / not in 연산자
# ────────────────────────────────────────────────────────────

sentence = '파이썬은 재미있는 언어입니다.'

# in: 포함 여부, not in: 미포함 여부를 True/False로 반환합니다.
print("파이썬" in sentence)     # True
print("자바" not in sentence)   # True


# ────────────────────────────────────────────────────────────
# [6] f-string
# ────────────────────────────────────────────────────────────

item = '노트북'
price = 1500000

# f'' 접두사로 {} 안에 변수나 표현식을 바로 삽입합니다.
print(f"{item}의 가격은 {price}원 입니다.")

# int()로 감싸서 소수점 없이 출력합니다. (1.1 곱하면 float가 됩니다.)
print(f"부가세 포함 가격 : {int(price * 1.1)}원")


# ────────────────────────────────────────────────────────────
# [7] upper() / lower() / isupper() / islower()
# ────────────────────────────────────────────────────────────

text = 'Hello, Python!'

# upper()/lower(): 원본은 그대로이고 변환된 새 문자열을 반환합니다.
print(text.upper())       # HELLO, PYTHON!
print(text.lower())       # hello, python!
print("WORLD".isupper())  # True
print("world".islower())  # True


# ────────────────────────────────────────────────────────────
# [8] isX() 메서드 (문자열 특성 확인)
# ────────────────────────────────────────────────────────────

# isalpha(): 영문자로만 구성되어 있는지 확인합니다.
print('abc'.isalpha())            # True  (영문자만)

# isalnum(): 영문자 또는 숫자로만 구성되어 있는지 확인합니다.
print('abc123'.isalnum())         # True  (영문자+숫자)

# isdecimal(): 숫자로만 구성되어 있는지 확인합니다.
print('123'.isdecimal())          # True  (숫자만)

# isspace(): 공백(스페이스/탭/줄바꿈)으로만 구성되어 있는지 확인합니다.
print('   '.isspace())            # True  (공백만)

# istitle(): 각 단어가 대문자로 시작하는지 확인합니다.
print('This Is Title'.istitle())  # True  (각 단어 첫 글자가 대문자)


# ────────────────────────────────────────────────────────────
# [9] startswith() / endswith()
# ────────────────────────────────────────────────────────────

filename = 'report_2026.pdf'

# 파일명이 특정 문자열로 시작하거나 끝나는지 확인합니다.
print(filename.startswith("report"))  # True
print(filename.endswith(".pdf"))      # True
print(filename.endswith(".txt"))      # False


# ────────────────────────────────────────────────────────────
# [10] join() / split()
# ────────────────────────────────────────────────────────────

fruits = ['사과', '바나나', '딸기', '포도']

# join(): 구분자.join(리스트) 형태로 리스트를 하나의 문자열로 합칩니다.
print("-".join(fruits))    # 사과-바나나-딸기-포도

message = 'I love Python'

# split(): 문자열을 나눠서 리스트로 반환합니다. 기본은 공백 기준입니다.
print(message.split())     # ['I', 'love', 'Python']

diary = '''월요일
화요일
수요일'''

# '\n'을 기준으로 나누면 각 줄이 리스트의 항목이 됩니다.
print(diary.split('\n'))   # ['월요일', '화요일', '수요일']


# ────────────────────────────────────────────────────────────
# [11] rjust() / ljust() / center()
# ────────────────────────────────────────────────────────────

# rjust(): 오른쪽 정렬, ljust(): 왼쪽 정렬, center(): 가운데 정렬입니다.
print("Python".rjust(20))         #               Python
print("Python".ljust(20))         # Python
print("Python".center(20, "="))   # =======Python=======


# ────────────────────────────────────────────────────────────
# [12] strip() / lstrip() / rstrip()
# ────────────────────────────────────────────────────────────

messy = '   안녕하세요   '

# strip(): 양쪽, lstrip(): 왼쪽, rstrip(): 오른쪽 공백을 제거합니다.
print(messy.strip())    # 안녕하세요
print(messy.lstrip())   # 안녕하세요   (오른쪽 공백 남음)
print(messy.rstrip())   #    안녕하세요 (왼쪽 공백 남음)


# ────────────────────────────────────────────────────────────
# [13] ord() / chr()
# ────────────────────────────────────────────────────────────

# ord(): 문자 → 유니코드 코드 포인트 숫자로 변환합니다.
# chr(): 숫자 → 유니코드 문자로 변환합니다.
print(ord("A"))              # 65
print(chr(97))               # a
print(chr(ord('A') + 1))     # B  (A의 코드포인트+1 → B)
