# 2. Raw String: r'' 접두사 → 백슬래시를 문자 그대로 처리합니다.
#    파일 경로, 정규 표현식에서 유용합니다.

# 3. 멀티라인: ''' ''' 또는 """ """ → 줄바꿈 포함 가능합니다.

# 4. 슬라이스: [시작:끝] → 끝 인덱스는 미포함, 생략 가능합니다.
#    [시작:]  → 시작부터 끝까지
#    [:끝]   → 처음부터 끝 직전까지
#    [-3:]   → 뒤에서 3번째부터 끝까지

# 5. f-string: f'{변수}' → 문자열 안에 변수/표현식 삽입합니다.

# 6. 주요 메서드 정리
#    upper() / lower()               대소문자 변환 (원본 불변)
#    isupper() / islower()           대소문자 여부 확인
#    isalpha() / isalnum()           문자/영숫자 여부 확인
#    isdecimal() / isspace()         숫자/공백 여부 확인
#    istitle()                       타이틀케이스 여부 확인
#    startswith() / endswith()       시작/끝 문자열 확인
#    join(리스트) / split(구분자)    합치기/나누기
#    rjust() / ljust() / center()    정렬 (너비, 채움문자)
#    strip() / lstrip() / rstrip()   공백 제거
#    ord() / chr()                   문자 ↔ 유니코드 숫자 변환

# ────────────────────────────────────────────────────────────
# ❌ 실수 1: 거듭제곱(**)과 곱하기(*) 혼동
# ────────────────────────────────────────────────────────────

price = 1500000

# ❌ 틀린 코드 — **는 거듭제곱이라 완전히 다른 값이 나옵니다.
# price ** 0.1   # price의 0.1승 → 약 97.6 (의도와 전혀 다름)

# ✅ 올바른 코드 — 10%는 * 0.1 또는 * 1.1을 사용합니다.
tax = price * 0.1           # 10% 금액: 150000.0
final = price * 1.1         # 부가세 포함: 1650000.0
final_int = int(price * 1.1)  # 정수로: 1650000

print(f"부가세 포함: {final_int}원")

# ────────────────────────────────────────────────────────────
# ❌ 실수 2: 음수 인덱스 슬라이스 방향 혼동
# ────────────────────────────────────────────────────────────

word = 'Python'
# P   y   t   h   o   n
# 0   1   2   3   4   5
# -6  -5  -4  -3  -2  -1

# ❌ 틀린 코드 — 슬라이스는 앞 인덱스 < 뒤 인덱스 여야 합니다.
# word[-1:3]  # -1(=5)에서 3으로 거꾸로 → 아무것도 안 나옴

# ✅ 올바른 코드 — 뒤에서 N글자는 [-N:]으로 씁니다.
print(word[-3:])   # hon (뒤에서 3번째부터 끝까지)
print(word[-1:])   # n   (마지막 문자만)

# ────────────────────────────────────────────────────────────
# ❌ 실수 3: 슬라이스 인덱스 생략 규칙 미숙지
# ────────────────────────────────────────────────────────────

# 슬라이스에서 인덱스를 생략하면 아래와 같이 동작합니다.
# [시작:]  → 시작부터 끝까지 (끝 생략 = 마지막까지)
# [:끝]   → 처음부터 끝 직전까지 (시작 생략 = 처음부터)

# ❌ 헷갈리는 코드
# word[-3:5]  # -3(=3)부터 5 직전까지 → 'ho' (의도와 다를 수 있음)

# ✅ 명확한 코드
print(word[-3:])   # hon ← 끝을 생략해야 마지막까지 포함됩니다.

# ────────────────────────────────────────────────────────────
# ❌ 실수 4: 삼중 따옴표 문자열 안에 # 주석 혼입
# ────────────────────────────────────────────────────────────

# ❌ 틀린 코드 — 삼중 따옴표 안의 #은 주석이 아니라 문자열의 일부입니다.
# diary = '''월요일
# # 화요일     ← #이 내용 안에 들어가 버림!
# # 수요일'''

# ✅ 올바른 코드 — 삼중 따옴표 블록 안에는 주석을 쓰지 않습니다.
diary = '''월요일
화요일
수요일'''
print(diary.split('\n'))   # ['월요일', '화요일', '수요일']

# ────────────────────────────────────────────────────────────
# ❌ 실수 5: center() 채움문자 인자 누락
# ────────────────────────────────────────────────────────────

# ❌ 틀린 코드 — 채움문자 없이 쓰면 공백으로 채워집니다.
print("Python".center(20))      # '       Python       ' (공백으로 채움)

# ✅ 올바른 코드 — 두 번째 인자에 채움문자를 지정합니다.
print("Python".center(20, "="))  # =======Python=======
