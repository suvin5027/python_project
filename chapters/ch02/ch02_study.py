# =============================================================================
# 연습 1. 불리언 값
# =============================================================================

# (1) True와 False를 각각 출력합니다.
print(True)
print(False)

# (2) type()으로 True의 타입을 확인합니다.
print(type(True))


# =============================================================================
# 연습 2. 비교 연산자
# =============================================================================

# (1) 두 수가 같은지 == 로 비교합니다.
print(42 == 42)

# (2) 두 수가 다른지 != 로 비교합니다.
print(10 != 20)

# (3) > 와 < 로 크기를 비교합니다.
print(100 < 50)
print(100 > 50)

# (4) 문자열을 == 로 비교합니다. 대소문자가 다르면 False입니다.
print("python" == "Python")


# =============================================================================
# 연습 3. 불리언 연산자
# =============================================================================

# (1) and 연산자를 사용합니다.
print(True and False)

# (2) or 연산자를 사용합니다.
print(True or False)

# (3) not 연산자를 사용합니다.
print(not True)

# (4) 비교 연산자와 불리언 연산자를 함께 사용합니다.
# age가 20 이상이고(and) 30 미만인지 확인합니다.
age = 25
print((20 <= age) and (age < 30))


# =============================================================================
# 연습 4. if 문
# =============================================================================

# weather가 "맑음"이면 날씨 메시지를 출력합니다.
weather = "맑음"
if weather == "맑음":
	print("오늘은 날씨가 좋습니다.")


# =============================================================================
# 연습 5. if / else 문
# =============================================================================

# temperature가 20 이상이면 "따뜻합니다.", 그렇지 않으면 "쌀쌀합니다."를 출력합니다.
temperature = 18
if temperature >= 20:
	print("따뜻합니다.")
else:
	print("쌀쌀합니다.")


# =============================================================================
# 연습 6. if / elif / else 문
# =============================================================================

# score에 따라 학점을 출력합니다.
score = 98
if score >= 90:
	print("A학점입니다.")
elif score >= 80:
	print("B학점입니다.")
elif score >= 70:
	print("C학점입니다.")
elif score >= 60:
	print("D학점입니다.")
else:
	print("F학점입니다.")


# =============================================================================
# 연습 7. 종합 미니 프로그램
# =============================================================================

# 이름이 "박수빈"이면 이름과 나이를 출력하고, 다르면 처음 인사를 출력합니다.
my_name = "박수빈"
my_age = 32
if my_name == "박수빈":
	print("안녕하세요, [" + my_name + "]님 나이는 [" + str(my_age) + "]살 이군요.")
else:
	print("처음 뵙겠습니다. [" + my_name + "]님!")
