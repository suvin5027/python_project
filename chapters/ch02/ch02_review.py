# 1. 불리언 값 (Boolean Values)
#    → True와 False 두 가지 값만 가집니다.
#    → 반드시 첫 글자를 대문자로 씁니다. 따옴표를 사용하지 않습니다.
#    → true → NameError, False = 2 + 2 → SyntaxError

# 2. 비교 연산자 (Comparison Operators)
#    → 두 값을 비교하여 True 또는 False를 반환합니다.
#    → ==  같다        !=  같지 않다
#    → <   보다 작다   >   보다 크다
#    → <=  작거나 같다  >=  크거나 같다
#    → 주의: = 는 할당, == 는 비교입니다.
#    → 42 == 42.0 → True (값이 같으면 타입이 달라도 같다고 평가됩니다)
#    → 42 == '42' → False (숫자와 문자열은 항상 다릅니다)

# 3. 불리언 연산자 (Boolean Operators)
#    → and : 양쪽이 모두 True일 때만 True입니다.
#    → or  : 하나라도 True이면 True입니다. (둘 다 False여야 False입니다.)
#    → not : 불리언 값을 반전시킵니다. (단항 연산자)
#    → 우선순위: not → and → or

# 4. 조건 (Condition)
#    → True 또는 False로 평가되는 표현식입니다.
#    → 흐름 제어문(if, elif, else)에서 어떤 코드를 실행할지 결정합니다.

# 5. 코드 블록 (Blocks of Code)
#    → 들여쓰기로 묶인 코드의 집합입니다.
#    → 규칙 1: 들여쓰기가 증가하면 새 블록이 시작됩니다.
#    → 규칙 2: 블록은 다른 블록을 포함할 수 있습니다.
#    → 규칙 3: 들여쓰기가 줄어들면 블록이 끝납니다.
#    → 규칙 4: 콜론(:)으로 끝나는 문장 다음에 새 블록이 시작됩니다.

# 6. if / elif / else 문
#    → if : 조건이 True일 때만 실행합니다.
#    → elif : 앞 조건이 False일 때 다음 조건을 검사합니다.
#    → else : 모든 조건이 False일 때 실행합니다.
#    → 처음으로 True인 블록 하나만 실행하고 나머지는 건너뜁니다.
#    → elif 순서가 중요합니다! 조건 순서가 바뀌면 의도치 않은 결과가 나올 수 있습니다.


