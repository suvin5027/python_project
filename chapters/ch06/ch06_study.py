# ============================================================
# [1] 리스트 만들기 & 인덱스
# ============================================================

# 좋아하는 음식 3가지 리스트입니다.
foods = ["딸기", "바나나", "김치찌개"]

# 첫 번째 항목을 출력합니다.
print(foods[0])

# 마지막 항목을 음수 인덱스로 출력합니다.
print(foods[-1])

# 두 번째 항목을 다른 음식으로 변경합니다.
foods[1] = "피자"
print(foods[1])


# ============================================================
# [2] 슬라이스
# ============================================================

numbers = [10, 20, 30, 40, 50, 60]

# [20, 30, 40]만 슬라이스로 출력합니다.
print(numbers[1:4])

# 앞의 3개 항목을 슬라이스로 출력합니다. (시작 인덱스 생략)
print(numbers[:3])

# 마지막 2개 항목을 음수 인덱스로 출력합니다.
print(numbers[-2:])


# ============================================================
# [3] 리스트 메서드
# ============================================================

animals = ['cat', 'dog', 'bird']

# 'fish'를 리스트 끝에 추가합니다.
animals.append("fish")

# 인덱스 1 위치에 'hamster'를 삽입합니다.
animals.insert(1, "hamster")
print(animals)

# 'dog'를 값으로 찾아 제거합니다.
animals.remove("dog")
print(animals)

# 알파벳 순으로 정렬합니다.
animals.sort()
print(animals)

# 정렬된 순서를 역순으로 뒤집습니다.
animals.reverse()
print(animals)


# ============================================================
# [4] for 루프 + 리스트
# ============================================================

fruits = ['apple', 'banana', 'cherry', 'grape']

# for 루프로 fruits의 각 항목을 출력합니다.
for item in fruits:
	print(item)

# enumerate()로 인덱스와 항목을 함께 출력합니다.
for index, item in enumerate(fruits):
	print(index, "번 :", item)


# ============================================================
# [5] in / not in 연산자
# ============================================================

colors = ['red', 'green', 'blue']

# 'green'이 colors에 있는지 확인합니다.
print("green" in colors)

# 'yellow'가 colors에 없는지 확인합니다.
print("yellow" not in colors)

# 'red'가 colors에 있으면 "빨강 있음"을 출력합니다.
if("red" in colors):
	print("빨강 있음")
else:
	print("빨강 없음")


# ============================================================
# [6] 다중 할당 트릭 (Tuple Unpacking)
# ============================================================

person = ['수빈', 25, '개발자']

# 다중 할당으로 리스트 값을 세 변수에 한 번에 대입합니다.
name, age, job = person

# 각 변수를 출력합니다.
print(name)
print(age)
print(job)


# ============================================================
# [7] 복합 할당 연산자
# ============================================================

score = 100

score += 50   # 100 + 50 = 150
score -= 30   # 150 - 30 = 120
score *= 2    # 120 * 2  = 240
score //= 4   # 240 // 4 = 60
print(score)  # 60


# ============================================================
# [8] 가변 vs 불변 + 참조
# ============================================================

# list_b = list_a는 주소를 복사하므로 같은 리스트를 가리킵니다.
list_a = [1, 2, 3]
list_b = list_a
list_b[0] = 99
print(list_a)  # [99, 2, 3] — list_a도 같이 바뀝니다.
print(list_b)  # [99, 2, 3]

# copy.copy()로 진짜 독립 복사본을 만듭니다.
import copy

list_c = copy.copy(list_a)
list_c[0] = 0
print(list_a)  # [99, 2, 3] — 원본은 그대로입니다.
print(list_c)  # [0, 2, 3]  — list_c만 변경됩니다.


# ============================================================
# [9] 튜플 (Tuple)
# ============================================================

# 튜플을 만들어 cities 변수에 저장합니다.
cities = ("서울", "부산", "제주")

# 두 번째 항목을 출력합니다.
print(cities[1])

# list()로 튜플을 리스트로 변환합니다.
print(list(cities))

# 항목이 하나인 튜플은 쉼표가 반드시 필요합니다.
single = (42,)
print(type(single))
