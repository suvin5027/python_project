# ----------------------------------------
# ❌ 실수 1: 슬라이스 — 마지막 2개 항목
# ----------------------------------------
numbers = [10, 20, 30, 40, 50, 60]

# ❌ 틀린 코드
print(numbers[3:-1])  # [40, 50] — 마지막(60)이 빠짐

# ✅ 올바른 코드
print(numbers[-2:])   # [50, 60] — 뒤에서 2개

# 핵심: numbers[시작:-1] 에서 -1은 마지막을 "포함하지 않는" 기준점입니다.
#       마지막 N개를 가져오려면 [-N:] 을 사용합니다.


# ----------------------------------------
# ❌ 실수 2: insert() 대신 인덱스 대입 사용
# ----------------------------------------
animals = ['cat', 'dog', 'bird']

# ❌ 틀린 코드 — = 대입은 기존 값을 교체합니다.
animals_wrong = ['cat', 'dog', 'bird']
animals_wrong[1] = 'hamster'
print(animals_wrong)  # ['cat', 'hamster', 'bird'] — dog가 사라짐!

# ✅ 올바른 코드 — insert()는 기존 값을 뒤로 밀고 삽입합니다.
animals_right = ['cat', 'dog', 'bird']
animals_right.insert(1, 'hamster')
print(animals_right)  # ['cat', 'hamster', 'dog', 'bird'] — dog가 살아있음!

# 핵심: 인덱스[n] = 값  →  교체 (기존 값 사라짐)
#       insert(n, 값)  →  삽입 (기존 값은 뒤로 밀림)


# ----------------------------------------
# ❌ 실수 3: remove() 대신 del 사용
# ----------------------------------------
# ❌ 틀린 코드 — del은 인덱스로 삭제합니다.
# del animals[2]  # 인덱스 2번 항목 삭제 (값이 무엇인지 신경 안 씁니다.)

# ✅ 올바른 코드 — remove()는 값으로 찾아 삭제합니다.
test = ['cat', 'hamster', 'dog', 'bird']
test.remove('dog')   # 'dog'라는 값을 찾아 삭제합니다.
print(test)          # ['cat', 'hamster', 'bird']

# 핵심: del list[인덱스]  →  인덱스 위치로 삭제
#       list.remove(값)  →  값을 찾아 삭제 (첫 번째 것만)


# ----------------------------------------
# ❌ 실수 4: not in 미사용
# ----------------------------------------
colors = ['red', 'green', 'blue']

# ❌ 틀린 코드 — "없는지" 확인하는 게 아니라 "있는지" 확인합니다.
print("yellow" in colors)      # False — 'yellow'가 있는지 확인

# ✅ 올바른 코드
print("yellow" not in colors)  # True  — 'yellow'가 없는지 확인

# 핵심: 없는지 확인 → not in / 있는지 확인 → in


# ----------------------------------------
# ❌ 실수 5: sort(reverse=True) vs reverse()
# ----------------------------------------
sample = ['bird', 'cat', 'fish', 'hamster']

# sort(reverse=True): 정렬하면서 동시에 내림차순으로 만듭니다.
sample_a = sample[:]
sample_a.sort(reverse=True)
print(sample_a)  # ['hamster', 'fish', 'cat', 'bird'] (알파벳 내림차순)

# reverse(): 현재 순서를 그냥 뒤집기만 합니다. (정렬 기준 없음)
sample_b = sample[:]
sample_b.reverse()
print(sample_b)  # ['hamster', 'fish', 'cat', 'bird'] (현재 순서 반전)

# 위 예시는 이미 정렬된 상태라 결과가 같지만, 원래 순서가 다르면 결과도 달라집니다.
# 핵심: "정렬 후 뒤집기" → sort(reverse=True)
#       "현재 순서 그대로 뒤집기" → reverse()
