# 1. 리스트 기본
#    - 대괄호 [] 사용, 항목은 쉼표로 구분합니다.
#    - 인덱스는 0부터 시작, 음수 인덱스는 뒤에서 셉니다.
#    - 슬라이스: list[시작:끝] → 끝 인덱스는 포함하지 않습니다.

# 2. 리스트 메서드
#    - append(값)         : 끝에 추가합니다.
#    - insert(인덱스, 값) : 해당 위치에 삽입합니다. (기존 항목은 뒤로 밀림)
#    - remove(값)         : 값을 찾아 첫 번째 것만 삭제합니다.
#    - sort()             : 오름차순 정렬합니다. (제자리 변경, 반환값 None)
#    - reverse()          : 현재 순서를 뒤집습니다. (제자리 변경, 반환값 None)
#    - index(값)          : 값의 인덱스를 반환합니다. (없으면 ValueError)

# 3. 가변 vs 불변
#    - 리스트: 가변(mutable) — 항목 추가/삭제/변경 가능합니다.
#    - 문자열, 튜플: 불변(immutable) — 내부 수정 불가합니다.

# 4. 참조 (References)
#    - 리스트 변수는 리스트 자체가 아닌 메모리 주소를 저장합니다.
#    - = 로 복사하면 주소만 복사 → 같은 리스트를 가리킵니다.
#    - 진짜 복사: copy.copy() (중첩 리스트는 copy.deepcopy())

# 5. 튜플
#    - 소괄호 () 사용, 불변입니다.
#    - 항목이 하나일 때는 뒤에 쉼표 필수: (42,)
#    - list() / tuple() 로 서로 변환 가능합니다.


